-- Optional bridge for accounts created through Supabase Auth.
CREATE OR REPLACE FUNCTION public.handle_auth_user_created()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE new_user_id bigint;
BEGIN
  INSERT INTO public.users (auth_user_id, full_name, email, phone, password_hash, status, email_verified_at)
  VALUES (NEW.id,
    COALESCE(NULLIF(NEW.raw_user_meta_data->>'full_name', ''), split_part(COALESCE(NEW.email, 'کاربر کارزینتل'), '@', 1)),
    NULLIF(NEW.email, ''), COALESCE(NULLIF(NEW.phone, ''), 'a' || substr(replace(NEW.id::text, '-', ''), 1, 14)),
    NULL, 'active', NEW.email_confirmed_at)
  ON CONFLICT (auth_user_id) DO UPDATE SET email = EXCLUDED.email
  RETURNING id INTO new_user_id;
  INSERT INTO public.role_user (role_id, user_id) SELECT id, new_user_id FROM public.roles WHERE name = 'customer' ON CONFLICT DO NOTHING;
  RETURN NEW;
END;
$$;
