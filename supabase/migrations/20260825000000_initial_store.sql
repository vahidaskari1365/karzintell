-- Row-level locking prevents two concurrent buyers from reserving the same stock.
CREATE OR REPLACE FUNCTION public.reserve_stock(p_order_id bigint, p_lines jsonb, p_warehouse_id integer DEFAULT NULL)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  line jsonb; v_warehouse_id integer := COALESCE(p_warehouse_id, (SELECT id FROM public.warehouses WHERE is_active ORDER BY id LIMIT 1));
  v_variant_id bigint; v_quantity integer; v_row public.inventory%ROWTYPE;
BEGIN
  IF v_warehouse_id IS NULL THEN RAISE EXCEPTION 'NO_ACTIVE_WAREHOUSE'; END IF;
  IF auth.role() <> 'service_role' AND NOT public.is_staff()
     AND NOT EXISTS (SELECT 1 FROM public.orders WHERE id = p_order_id AND user_id = public.current_app_user_id())
    THEN RAISE EXCEPTION 'FORBIDDEN' USING ERRCODE = '42501'; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.orders WHERE id = p_order_id AND status = 'pending_payment')
    THEN RAISE EXCEPTION 'ORDER_NOT_RESERVABLE'; END IF;
  FOR line IN SELECT * FROM jsonb_array_elements(p_lines) LOOP
    v_variant_id := (line->>'variantId')::bigint; v_quantity := (line->>'quantity')::integer;
    IF v_quantity IS NULL OR v_quantity <= 0 THEN RAISE EXCEPTION 'INVALID_QUANTITY'; END IF;
    SELECT * INTO v_row FROM public.inventory WHERE variant_id = v_variant_id AND warehouse_id = v_warehouse_id FOR UPDATE;
    IF NOT FOUND OR GREATEST(v_row.quantity - v_row.reserved, 0) < v_quantity THEN RAISE EXCEPTION 'OUT_OF_STOCK'; END IF;
    UPDATE public.inventory SET reserved = reserved + v_quantity, updated_at = now()
      WHERE variant_id = v_variant_id AND warehouse_id = v_warehouse_id;
    INSERT INTO public.stock_movements (variant_id, warehouse_id, type, quantity, qty_before, qty_after, reference_type, reference_id)
      VALUES (v_variant_id, v_warehouse_id, 'reserve', v_quantity, v_row.quantity, v_row.quantity, 'order', p_order_id);
  END LOOP;
END;
$$;
CREATE OR REPLACE FUNCTION public.release_stock(p_order_id bigint, p_lines jsonb, p_warehouse_id integer DEFAULT NULL)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE line jsonb; v_warehouse_id integer := COALESCE(p_warehouse_id, (SELECT id FROM public.warehouses WHERE is_active ORDER BY id LIMIT 1));
  v_variant_id bigint; v_quantity integer;
BEGIN
  IF auth.role() <> 'service_role' AND NOT public.is_staff()
     AND NOT EXISTS (SELECT 1 FROM public.orders WHERE id = p_order_id AND user_id = public.current_app_user_id())
    THEN RAISE EXCEPTION 'FORBIDDEN' USING ERRCODE = '42501'; END IF;
  FOR line IN SELECT * FROM jsonb_array_elements(p_lines) LOOP
    v_variant_id := (line->>'variantId')::bigint; v_quantity := (line->>'quantity')::integer;
    UPDATE public.inventory SET reserved = GREATEST(reserved - v_quantity, 0), updated_at = now()
      WHERE variant_id = v_variant_id AND warehouse_id = v_warehouse_id;
    INSERT INTO public.stock_movements (variant_id, warehouse_id, type, quantity, qty_before, qty_after, reference_type, reference_id)
