CREATE OR REPLACE FUNCTION public.has_permission(permission_name text)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.users u
    WHERE u.auth_user_id = auth.uid() AND u.status = 'active' AND u.deleted_at IS NULL
      AND (
        EXISTS (
          SELECT 1 FROM public.role_user ru
          JOIN public.permission_role pr ON pr.role_id = ru.role_id
          JOIN public.permissions p ON p.id = pr.permission_id
          WHERE ru.user_id = u.id AND p.name = permission_name
        )
        OR EXISTS (
          SELECT 1 FROM public.permission_user pu
          JOIN public.permissions p ON p.id = pu.permission_id
          WHERE pu.user_id = u.id AND pu.type = 'allow' AND p.name = permission_name
        )
      )
      AND NOT EXISTS (
        SELECT 1 FROM public.permission_user pu
        JOIN public.permissions p ON p.id = pu.permission_id
        WHERE pu.user_id = u.id AND pu.type = 'deny' AND p.name = permission_name
      )
  );
$$;
