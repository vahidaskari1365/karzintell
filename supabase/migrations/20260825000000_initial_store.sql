CREATE TABLE IF NOT EXISTS public.verification_codes (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  channel     TEXT NOT NULL,
  target      VARCHAR(190) NOT NULL,
  code_hash   VARCHAR(255) NOT NULL,
