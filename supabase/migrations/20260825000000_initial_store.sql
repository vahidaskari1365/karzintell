RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN UPDATE public.users SET deleted_at = now(), status = 'suspended' WHERE auth_user_id = OLD.id; RETURN OLD; END;
$$;
