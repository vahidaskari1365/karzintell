CREATE OR REPLACE FUNCTION public.refresh_inventory_snapshot()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_variant_id bigint := COALESCE(NEW.variant_id, OLD.variant_id);
  v_warehouse_id integer := COALESCE(NEW.warehouse_id, OLD.warehouse_id);
  v_available integer;
  v_threshold integer;
  v_alert_type text;
BEGIN
  UPDATE public.product_variants
  SET stock_total = COALESCE((SELECT SUM(GREATEST(i.quantity - i.reserved, 0))::integer
                              FROM public.inventory i WHERE i.variant_id = v_variant_id), 0)
  WHERE id = v_variant_id;

  SELECT GREATEST(quantity - reserved, 0), low_stock_threshold
    INTO v_available, v_threshold
  FROM public.inventory WHERE variant_id = v_variant_id AND warehouse_id = v_warehouse_id;
  IF NOT FOUND THEN RETURN COALESCE(NEW, OLD); END IF;

  v_alert_type := CASE WHEN v_available <= 0 THEN 'out_of_stock'
                       WHEN v_available <= v_threshold THEN 'low_stock'
                       ELSE NULL END;
  UPDATE public.stock_alerts
  SET status = 'resolved', resolved_at = now(), updated_at = now()
  WHERE variant_id = v_variant_id AND warehouse_id = v_warehouse_id AND status = 'open'
    AND (v_alert_type IS NULL OR alert_type <> v_alert_type);
  IF v_alert_type IS NOT NULL THEN
    INSERT INTO public.stock_alerts (variant_id, warehouse_id, available, threshold, alert_type, status, updated_at)
    VALUES (v_variant_id, v_warehouse_id, v_available, v_threshold, v_alert_type, 'open', now())
    ON CONFLICT (variant_id, warehouse_id, alert_type, status)
    DO UPDATE SET available = EXCLUDED.available, threshold = EXCLUDED.threshold, updated_at = now();
  END IF;
  RETURN COALESCE(NEW, OLD);
END;
$$;
DROP TRIGGER IF EXISTS inventory_snapshot_after_change ON public.inventory;
CREATE TRIGGER inventory_snapshot_after_change AFTER INSERT OR UPDATE OR DELETE ON public.inventory
FOR EACH ROW EXECUTE FUNCTION public.refresh_inventory_snapshot();

